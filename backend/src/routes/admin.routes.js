const express = require('express')
const authenticate = require('../middleware/authenticate')
const authorizeAdmin = require('../middleware/authorizeAdmin')
const validate = require('../middleware/zodValidate')
const controller = require('../controllers/admin.controller')
const productController = require('../controllers/product.controller')
const adjustInventorySchema = require('../validators/adjustInventory.schema')
const createBrandSchema = require('../validators/createBrand.schema')
const createCategorySchema = require('../validators/createCategory.schema')
const updateBrandSchema = require('../validators/updateBrand.schema')
const updateCategorySchema = require('../validators/updateCategory.schema')
const createProductSchema = require('../validators/createProduct.schema')
const updateProductSchema = require('../validators/updateProduct.schema')
const createProductVariantSchema = require('../validators/createProductVariant.schema')
const updateProductVariantSchema = require('../validators/updateProductVariant.schema')

const router = express.Router()

router.use(authenticate)
router.use(authorizeAdmin(['admin', 'stock_manager', 'super_admin']))
router.get('/categories', controller.listAdminCategories)
router.post('/categories', validate(createCategorySchema), controller.createCategory)
router.patch('/categories/:categoryId', validate(updateCategorySchema), controller.updateCategory)
router.delete('/categories/:categoryId', controller.deleteCategory)
router.get('/brands', controller.listAdminBrands)
router.post('/brands', validate(createBrandSchema), controller.createBrand)
router.patch('/brands/:brandId', validate(updateBrandSchema), controller.updateBrand)
router.delete('/brands/:brandId', controller.deleteBrand)
router.get('/orders', controller.listOrders)
router.post('/orders/:orderId/confirm', controller.confirmOrder)
router.post('/orders/:orderId/cancel', controller.cancelOrder)
router.post('/orders/:orderId/ship', controller.shipOrder)
router.get('/inventory', controller.listInventory)
router.post('/inventory/:variantId/adjust', validate(adjustInventorySchema), controller.adjustInventory)
router.get('/inventory/movements', controller.listInventoryMovements)
router.post('/products', validate(createProductSchema), productController.createProduct)
router.patch('/products/:productId', validate(updateProductSchema), productController.updateProduct)
router.delete('/products/:productId', productController.deleteProduct)
router.get('/products/:productId/variants', productController.listProductVariants)
router.post('/products/:productId/variants', validate(createProductVariantSchema), productController.createProductVariant)
router.patch('/variants/:variantId', validate(updateProductVariantSchema), productController.updateProductVariant)
router.delete('/variants/:variantId', productController.deleteProductVariant)
router.get('/users', authorizeAdmin(['admin', 'super_admin']), controller.listUsers)
router.get('/users/:userId', authorizeAdmin(['admin', 'super_admin']), controller.getUser)
router.get('/audit-logs', authorizeAdmin(['super_admin']), controller.listAuditLogs)

module.exports = router
